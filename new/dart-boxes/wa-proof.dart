// הערה: 4 "מגני-ההכרעה" של בדיקת-ה-JS קוראים את מקור-ה-mjs עצמו (regex על טקסט-הקובץ) —
//   אלה תלויי-מקור-JS ולא התנהגות חוצה-שפות, ולכן מדולגים כאן (חוק המקרה-תלוי-ריצה-JS).
import 'dart:convert';
import 'wa.dart' as W;

int n = 0, fails = 0;
void eq(String name, Object? got, Object? want) {
  final g = jsonEncode(got), w = jsonEncode(want);
  if (g != w) {
    print('✗ $name: got $g want $w');
    fails++;
  } else {
    n++;
  }
}

void main() {
  // ── waDigits (wa.ts:14-29) ──
  eq('טלפון מקומי מעוצב', W.waDigits('050-123-4567'), '972501234567');
  eq('+972 עם ה-0 המקומי', W.waDigits('+972 050-123-4567'), '972501234567');
  eq('קידומת-חיוג 00972', W.waDigits('00972501234567'), '972501234567');
  eq('ישראלי בלי 0 מוביל', W.waDigits('501234567'), '972501234567');
  eq('בינלאומי 00 כללי', W.waDigits('0044 20 7946 0958'), '442079460958');
  eq('0-מוביל באורך לא-תקין ⇒ null', W.waDigits('05012'), null);
  eq('קצר מגבול E.164 ⇒ null', W.waDigits('123'), null);
  eq('ריק ⇒ null', W.waDigits(''), null);
  eq('בלי ספרות ⇒ null', W.waDigits('אין טלפון'), null);

  // ── waLink (wa.ts:32-37) ──
  eq('קישור בלי טקסט', W.waLink('050-123-4567'), 'https://wa.me/972501234567');
  eq('טקסט עברי מקודד', W.waLink('050-123-4567', 'שלום'),
      'https://wa.me/972501234567?text=%D7%A9%D7%9C%D7%95%D7%9D');
  eq('רווחים-בלבד = בלי ?text', W.waLink('050-123-4567', '   '),
      'https://wa.me/972501234567');
  eq('trim לפני הקידוד', W.waLink('050-123-4567', '  היי  '),
      'https://wa.me/972501234567?text=' + Uri.encodeComponent('היי'));
  eq('טלפון לא-תקין ⇒ null גם עם טקסט', W.waLink('אבג', 'היי'), null);

  // ── נוסחי-ההודעה (wa.ts:52-68) — ברירות-מחדל, נפילת-ארגון, דריסות ──
  eq('הודעת-מסירה', W.waDeliveryText('מאור החסד', 'כהן'),
      'שלום משפחת כהן, משלוח ממאור החסד בדרך אליכם היום 🚚');
  eq('הכרעה 1: ארגון ריק ⇒ העמותה', W.waDeliveryText('  ', 'לוי'),
      'שלום משפחת לוי, משלוח מהעמותה בדרך אליכם היום 🚚');
  eq('תזכורת-תשלום: עיגול+he-IL', W.waPaymentText('מאור', 'חוג ציור', 1234.6),
      'שלום, תזכורת ידידותית ממאור: יתרה לתשלום עבור חוג ציור — ₪1,235. תודה רבה!');
  eq('ברכת יום-הולדת', W.waBirthdayText('מאור', 'דנה'),
      'מזל טוב לדנה ליום ההולדת! 🎂 באהבה, מאור');
  eq('הכרעה 2: דריסת-ארגון גוברת',
      W.waBirthdayText('מאור', 'דנה', {
        'templates': {'wa.birthday': 'יומולדת שמח {first}! מ{org}'}
      }),
      'יומולדת שמח דנה! ממאור');
  eq('הכרעה 2: דריסה ריקה ⇒ ברירת-המחדל',
      W.waBirthdayText('מאור', 'דנה', {
        'templates': {'wa.birthday': '   '}
      }),
      'מזל טוב לדנה ליום ההולדת! 🎂 באהבה, מאור');
  eq('שם-משפחה ריק — trim על השם המורכב', W.waDeliveryText('מאור', ''),
      'שלום משפחת, משלוח ממאור בדרך אליכם היום 🚚');

  if (fails > 0) {
    print('❌ קופסת-וואטסאפ (Dart): $fails אי-התאמות מול golden ה-JS');
    throw StateError('wa dart proof failed');
  }
  print('✓ קופסת-וואטסאפ (Dart): $n דוגמאות-חוזה (ספרות·קישור·3 נוסחים·דריסות) — '
      'פלט זהה-ביט ל-JS · שתי המערכות על אותה קופסה');
}
