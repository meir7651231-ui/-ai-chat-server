import { nameSortKey } from './name-sort-key.mjs';
let f = 0;
const ok = (cond, msg) => { if (!cond) { console.error('✗ ' + msg); f = 1; } };
// שקעים כרוח-המקור (maor/src/lib/validate.ts): נרמול-חיפוש עברי + סט-תארים
const normSearch = (t) =>
  String(t || '')
    .toLowerCase()
    .replace(/[֑-ׇ]/g, '')
    .replace(/[ךםןףץ]/g, (ch) => ({ ך: 'כ', ם: 'מ', ן: 'נ', ף: 'פ', ץ: 'צ' })[ch])
    .replace(/['"׳״\-–._]/g, '')
    .trim();
const titles = new Set(['הרב', 'מר', 'משפחת']);
const k = (t) => nameSortKey(t, normSearch, titles);
// 1) מיון קנוני
// הנרמול (שקע-normSearch) ממיר ן-סופית ⇒ 'בנ' — עקבי עם סעיף 3 ('כהנ')
ok(k('רחל בן צבי') === 'בנ צבי רחל', "'רחל בן צבי' לא מוין ל-'בנ צבי רחל': " + k('רחל בן צבי'));
// 2) חסין-סדר — שני הסדרים ⇒ אותו מפתח
ok(k('בן צבי רחל') === k('רחל בן צבי'), 'שני סדרי-השם לא נתנו מפתח זהה');
// 3) הסרת-תואר + נרמול ן-סופית
ok(k('הרב משה כהן') === 'כהנ משה', "'הרב משה כהן' ⇒ " + k('הרב משה כהן'));
// 4) תואר מוסר רק כטוקן-שלם — 'מרים' שורד את 'מר'
ok(k('מרים לוי') === 'לוי מרימ', "'מרים לוי' ⇒ " + k('מרים לוי'));
// 5) ריק ותואר-בלבד ⇒ ריק
ok(k('') === '', 'מחרוזת ריקה לא נתנה ריק');
ok(k('משפחת') === '', 'תואר-בלבד לא נתן ריק');
if (f) process.exit(1);
console.log('✓ name-sort-key: 5 דוגמאות-חוזה — ירוק');
