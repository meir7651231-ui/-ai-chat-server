export function expandQuery(q, norm, T) {
  const nq = norm(q);
  const out = [q];
  if (!nq) return out;
  for (const [heb, aliases] of Object.entries(makeXLAT(T))) {
    if (norm(heb) === nq) out.push(...aliases);
    else if (aliases.some((a) => norm(a) === nq)) out.push(heb);
  }
  return [...new Set(out)];
}
