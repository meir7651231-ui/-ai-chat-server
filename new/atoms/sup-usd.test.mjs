import { supUsd } from './sup-usd.mjs';
let f = 0;
const ok = (cond, msg) => { if (!cond) { console.error('✗ ' + msg); f = 1; } };
// 1) בלי היסטוריה
ok(supUsd({ usd: 100 }) === 100, 'דוגמה 1: ≠ 100');
// 2) hist מעורב — רק '$' נספר
ok(supUsd({ usd: 100, hist: [{ a: 50, c: '$', d: '2025-01-01' }, { a: 30, c: '₪', d: '2025-02-01' }] }) === 150, 'דוגמה 2: ≠ 150');
// 3) אובייקט ריק
ok(supUsd({}) === 0, 'דוגמה 3: ≠ 0');
// 4) usd=0 + שתי שורות-דולר
ok(supUsd({ usd: 0, hist: [{ a: 20, c: '$', d: '2024-05-05' }, { a: 5, c: '$', d: '2024-06-06' }] }) === 25, 'דוגמה 4: ≠ 25');
// 5) זיכוי שלילי מקוזז
ok(supUsd({ usd: 100, hist: [{ a: -40, c: '$', d: '2024-07-07' }] }) === 60, 'דוגמה 5: ≠ 60');
// 6) שורה בלי c אינה דולרית
ok(supUsd({ usd: 10, hist: [{ a: 99, d: '2024-08-08' }] }) === 10, 'דוגמה 6: ≠ 10');
if (f) process.exit(1);
console.log('✓ sup-usd: 6 דוגמאות-חוזה — ירוק');
