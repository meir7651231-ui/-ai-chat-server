import { signUpError } from './sign-up-error.mjs';
let f = 0;
const eq = (a, b, msg) => { if (a !== b) { console.error(`✗ ${msg} ⇒ ${JSON.stringify(a)}`); f = 1; } };

// 1) שם-ארגון רווחים בלבד — trim מנטרל
eq(signUpError('  ', 'משה', '050-1234567', 'a@b.com', '123456', '123456'),
  'שם הארגון הוא שדה חובה', 'שם-ארגון ריק לא נתפס');

// 2) איש-קשר ריק
eq(signUpError('עמותה', '', '050-1234567', 'a@b.com', '123456', '123456'),
  'שם איש הקשר הוא שדה חובה', 'איש-קשר ריק לא נתפס');

// 3) טלפון לא-תקין — אותיות + קצר-מדי
eq(signUpError('עמותה', 'משה', 'abc', 'a@b.com', '123456', '123456'),
  'מספר טלפון תקין הוא שדה חובה — נחזור אליכם לאישור', 'טלפון-אותיות לא נתפס');
eq(signUpError('עמותה', 'משה', '05', 'a@b.com', '123456', '123456'),
  'מספר טלפון תקין הוא שדה חובה — נחזור אליכם לאישור', 'טלפון-קצר לא נתפס');

// 4) אימייל בלי @
eq(signUpError('עמותה', 'משה', '050-1234567', 'ab.com', '123456', '123456'),
  'כתובת האימייל אינה תקינה', 'אימייל שבור לא נתפס');

// 5) סיסמה קצרה
eq(signUpError('עמותה', 'משה', '050-1234567', 'a@b.com', '12345', '12345'),
  'הסיסמה חייבת להיות לפחות 6 תווים', 'סיסמה קצרה לא נתפסה');

// 6) סיסמאות שונות
eq(signUpError('עמותה', 'משה', '050-1234567', 'a@b.com', '123456', '654321'),
  'הסיסמאות אינן זהות', 'אי-זהות סיסמאות לא נתפסה');

// 7) הכול תקין — כולל + ורווח בטלפון, רווחי-קצה באימייל
eq(signUpError('עמותה', 'משה', '+972 50-1234567', ' a@b.com ', '123456', '123456'),
  '', 'קלט תקין נפסל');

if (f) process.exit(1);
console.log('✓ sign-up-error: 7 דוגמאות-חוזה — ירוק');
