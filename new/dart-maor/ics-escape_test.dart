// רתמת-זהב · ics-escape — assert-ים = דוגמאות-החוזה של בדיקת-ה-JS (זהות-ביט).
// קלטי-הבדיקה עוברים JS-side דרך JSON.parse ⇒ המחרוזות הממשיות שלהלן;
// אף אחת אינה מכילה \ ; , או שורה-חדשה ⇒ הפלט זהה לקלט (Golden 12).
import 'ics-escape.dart';

void main() {
  const cases = <List<String>>[
    ['', ''],
    ['אבג', 'אבג'],
    ['כהן לוי', 'כהן לוי'],
    ['abc', 'abc'],
    ['a@b.com', 'a@b.com'],
    ['2026-08-24', '2026-08-24'],
    ['2026-08-24T12:00:00', '2026-08-24T12:00:00'],
    ['0501234567', '0501234567'],
    ['03-1234567', '03-1234567'],
    ['https://x.co', 'https://x.co'],
    ['שלום עולם', 'שלום עולם'],
    ['12', '12'],
  ];
  for (final c in cases) {
    final got = icsEscape(c[0]);
    assert(got == c[1], '✗ ${c[0]} ⇒ $got ≠ ${c[1]}');
  }
  print('✓ ics-escape (Dart): 12 דוגמאות-חוזה (Golden) — ירוק');
}
