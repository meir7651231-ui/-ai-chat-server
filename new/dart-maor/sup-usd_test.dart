/// בדיקת חוט · sup-usd (Dart) — כל 6 דוגמאות-החוזה + שיקוף sup-usd.test.mjs.
import 'sup-usd.dart';

void ok(bool cond, String msg) {
  if (!cond) throw StateError('✗ ' + msg);
}

void main() {
  // 1) בלי היסטוריה
  ok(supUsd({'usd': 100}) == 100, 'דוגמה 1: ≠ 100');
  // 2) hist מעורב — רק '$' נספר
  ok(
    supUsd({
          'usd': 100,
          'hist': [
            {'a': 50, 'c': '\$', 'd': '2025-01-01'},
            {'a': 30, 'c': '₪', 'd': '2025-02-01'},
          ],
        }) ==
        150,
    'דוגמה 2: ≠ 150',
  );
  // 3) אובייקט ריק — חסר usd ⇒ 0, חסר hist ⇒ []
  ok(supUsd({}) == 0, 'דוגמה 3: ≠ 0');
  // 4) usd=0 + שתי שורות-דולר
  ok(
    supUsd({
          'usd': 0,
          'hist': [
            {'a': 20, 'c': '\$', 'd': '2024-05-05'},
            {'a': 5, 'c': '\$', 'd': '2024-06-06'},
          ],
        }) ==
        25,
    'דוגמה 4: ≠ 25',
  );
  // 5) זיכוי שלילי מקוזז
  ok(
    supUsd({
          'usd': 100,
          'hist': [
            {'a': -40, 'c': '\$', 'd': '2024-07-07'},
          ],
        }) ==
        60,
    'דוגמה 5: ≠ 60',
  );
  // 6) שורה בלי c אינה דולרית
  ok(
    supUsd({
          'usd': 10,
          'hist': [
            {'a': 99, 'd': '2024-08-08'},
          ],
        }) ==
        10,
    'דוגמה 6: ≠ 10',
  );

  // נאמנות-JS נוספת (מגזרת המקור, לא מרחיבה את החוזה):
  // usd=null ⇒ falsy ⇒ 0 (כמו `null || 0`)
  ok(supUsd({'usd': null, 'hist': []}) == 0, 'usd:null ⇒ ≠ 0');
  // hist=null ⇒ ?? [] (nullish)
  ok(supUsd({'usd': 7, 'hist': null}) == 7, 'hist:null ⇒ ≠ 7');
  // c='' (לא '$') לא נספר
  ok(
    supUsd({
          'usd': 1,
          'hist': [
            {'a': 5, 'c': '', 'd': '2024-01-01'},
          ],
        }) ==
        1,
    "c:'' ⇒ ≠ 1",
  );
  // שברים — אריתמטיקת float64 (חוק-17): 0.1+0.2 של JS
  ok(
    supUsd({
          'usd': 0,
          'hist': [
            {'a': 0.1, 'c': '\$', 'd': '2024-01-01'},
            {'a': 0.2, 'c': '\$', 'd': '2024-01-02'},
          ],
        }) ==
        0.30000000000000004,
    'float64: 0.1+0.2 ≠ 0.30000000000000004',
  );

  print('OK');
}
