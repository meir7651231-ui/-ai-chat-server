// חמש דוגמאות-החוזה זהות ביט-אחר-ביט למקור-ה-JS new/atoms/sup-last.test.mjs
// (שהוא-עצמו מתרגם את 5 הדוגמאות המחייבות של sup-last.contract.md):
//   1) {last:'2026-03-01'} (בלי hist)                              ⇒ '2026-03-01'
//   2) {last:'2026-03-01', hist:[{d:'2026-05-10'},{d:'2025-01-01'}]} ⇒ '2026-05-10'
//   3) {last:'2026-06-01', hist:[{d:'2026-05-10'}]}                 ⇒ '2026-06-01'
//   4) {}                                                          ⇒ ''
//   5) {hist:[{d:'2024-12-31'}]} (בלי last)                         ⇒ '2024-12-31'
// הפלט מחרוזת (לא מערך) ⇒ השוואת-שוויון ישירה; כלל-8 לא חל. כשל ⇒ StateError.
// הרצה: dart run --enable-asserts new/dart-maor/sup-last_test.dart  ⇒ OK + exit 0
import 'sup-last.dart';

void _ok(bool cond, String msg) {
  if (!cond) throw StateError('FAIL: $msg');
}

void main() {
  var n = 0;

  // מתרגם את לולאת-הבדיקה של ה-JS: זוגות [קלט, פלט-צפוי] ⇒ שוויון מדויק.
  final cases = <List<dynamic>>[
    // 1) בלי hist — הקבלה לבדה.
    [
      {'last': '2026-03-01'},
      '2026-03-01',
    ],
    // 2) ההיסטוריה מאוחרת מהקבלה — ההיסטוריה מנצחת.
    [
      {
        'last': '2026-03-01',
        'hist': [
          {'d': '2026-05-10'},
          {'d': '2025-01-01'},
        ],
      },
      '2026-05-10',
    ],
    // 3) הקבלה מאוחרת מההיסטוריה — הקבלה מנצחת.
    [
      {
        'last': '2026-06-01',
        'hist': [
          {'d': '2026-05-10'},
        ],
      },
      '2026-06-01',
    ],
    // 4) תורם בלי אף תרומה ⇒ '' (מפתח-חסר, לא null — כלל-2 מכוסה בהתנהגות ||).
    [<String, dynamic>{}, ''],
    // 5) היסטוריה בלבד, בלי last.
    [
      {
        'hist': [
          {'d': '2024-12-31'},
        ],
      },
      '2024-12-31',
    ],
  ];

  for (final c in cases) {
    final got = supLast(c[0] as Map);
    _ok(got == c[1], '${c[0]} ⇒ $got ≠ ${c[1]}');
    n++;
  }

  // assert חי (--enable-asserts) — מוכיח שהמנגנון פעיל.
  assert(supLast({'last': '2026-03-01'}) == '2026-03-01', 'assert-live guard');

  print('OK supLast: $n asserts passed');
}
