// בדיקת-חוזה (רתמת-זהב) · signUpError — מייבאת אך ורק את האטום-שלה (חוק-4).
// דוגמאות-החוזה זהות ביט-אחר-ביט למקור-ה-JS new/atoms/sign-up-error.test.mjs
// (7 דוגמאות + מקרה-הטלפון-הקצר = 8 קריאות). הפלט מחרוזת-יחידה — אין השוואת-מערכים
// (כלל-8 לא חל; ההשוואה got!=want ישירה).
// אם עובר ⇒ Dart≡JS.
// הרצה: dart run --enable-asserts new/dart-maor/sign-up-error_test.dart  ⇒ exit 0
import 'sign-up-error.dart';

void _eq(String got, String want, String label) {
  if (got != want) {
    throw StateError('FAIL [$label]: got="$got" want="$want"');
  }
}

void main() {
  var n = 0;

  // 1) שם-ארגון רווחים בלבד — trim מנטרל
  _eq(signUpError('  ', 'משה', '050-1234567', 'a@b.com', '123456', '123456'),
      'שם הארגון הוא שדה חובה', '1 שם-ארגון ריק');
  n++;

  // 2) איש-קשר ריק
  _eq(signUpError('עמותה', '', '050-1234567', 'a@b.com', '123456', '123456'),
      'שם איש הקשר הוא שדה חובה', '2 איש-קשר ריק');
  n++;

  // 3) טלפון לא-תקין — אותיות + קצר-מדי
  _eq(signUpError('עמותה', 'משה', 'abc', 'a@b.com', '123456', '123456'),
      'מספר טלפון תקין הוא שדה חובה — נחזור אליכם לאישור', '3a טלפון-אותיות');
  n++;
  _eq(signUpError('עמותה', 'משה', '05', 'a@b.com', '123456', '123456'),
      'מספר טלפון תקין הוא שדה חובה — נחזור אליכם לאישור', '3b טלפון-קצר');
  n++;

  // 4) אימייל בלי @
  _eq(signUpError('עמותה', 'משה', '050-1234567', 'ab.com', '123456', '123456'),
      'כתובת האימייל אינה תקינה', '4 אימייל שבור');
  n++;

  // 5) סיסמה קצרה
  _eq(signUpError('עמותה', 'משה', '050-1234567', 'a@b.com', '12345', '12345'),
      'הסיסמה חייבת להיות לפחות 6 תווים', '5 סיסמה קצרה');
  n++;

  // 6) סיסמאות שונות
  _eq(signUpError('עמותה', 'משה', '050-1234567', 'a@b.com', '123456', '654321'),
      'הסיסמאות אינן זהות', '6 סיסמאות שונות');
  n++;

  // 7) הכול תקין — כולל + ורווח בטלפון, רווחי-קצה באימייל
  _eq(
      signUpError(
          'עמותה', 'משה', '+972 50-1234567', ' a@b.com ', '123456', '123456'),
      '',
      '7 קלט תקין');
  n++;

  // assert חי (חוק: --enable-asserts) — מוכיח שהמנגנון פעיל.
  assert(signUpError('', '', '', '', '', '') == 'שם הארגון הוא שדה חובה',
      'assert-live guard');

  print('OK signUpError: $n asserts passed');
}
