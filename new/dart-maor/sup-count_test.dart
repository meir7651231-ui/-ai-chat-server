// בדיקת-חוזה · supCount — 6 דוגמאות-החוזה (מקבילות ל-new/atoms/sup-count.test.mjs)
// + הסגר-חוק-17 (ה-+ של JS = float64) שבגללו האטום נפל באימות-העוין.
// הרצה: dart run --enable-asserts sup-count_test.dart
import 'sup-count.dart';

int _f = 0;
void ok(bool cond, String msg) {
  if (!cond) {
    // ignore: avoid_print
    print('✗ $msg');
    _f = 1;
  }
}

void main() {
  // 1) מונה שמור בלבד
  ok(supCount({'count': 5}) == 5, 'דוגמה 1: {count:5} ≠ 5');
  // 2) קבלות + היסטוריה
  ok(supCount({'count': 2, 'hist': [{'a': 100}, {'a': 50}]}) == 4, 'דוגמה 2: 2+2 ≠ 4');
  // 3) רק שורות-חיוב חיוביות
  ok(supCount({'count': 0, 'hist': [{'a': 0}, {'a': -30}, {'a': 80}]}) == 1,
      'דוגמה 3: אפס/זיכוי נספרו');
  // 4) אובייקט ריק
  ok(supCount({}) == 0, 'דוגמה 4: {} ≠ 0');
  // 5) hist ריק
  ok(supCount({'count': 3, 'hist': []}) == 3, 'דוגמה 5: hist ריק שיבש את המונה');
  // 6) שורה בלי a
  ok(supCount({'count': 1, 'hist': [{}]}) == 1, 'דוגמה 6: שורה בלי a נספרה');

  // 7) הסגר חוק-17 — ה-+ של JS הוא float64:
  //    count=9007199254740993 (‏2^53+1) ⇒ ‏V8 מייצג כ-2^53 (9007199254740992);
  //    +1 (שורת-hist חיובית) ⇒ 9007199254740992 (‏2^53+1 חוזר ל-2^53).
  //    הטיוטה השבורה חיברה int64: 9007199254740993+1=9007199254740994 — סטייה.
  //    התיקון (toDouble) מחזיר 9007199254740992.0 — זהה ל-V8.
  final r7 = supCount({'count': 9007199254740993, 'hist': [{'a': 5}]});
  ok(r7 == 9007199254740992.0, 'דוגמה 7: חוק-17 — חיבור-int64 במקום float64 (קיבל $r7)');
  ok(r7 is double, 'דוגמה 7ב: תוצאת ה-+ של JS חייבת להיות double');

  // 8) count מחרוזת ⇒ שרשור (ה-+ של JS): '2'+1 = '21'
  ok(supCount({'count': '2', 'hist': [{'a': 9}]}) == '21', 'דוגמה 8: שרשור-מחרוזת נכשל');

  if (_f != 0) {
    throw StateError('sup-count: כשל בדוגמאות-החוזה');
  }
  // ignore: avoid_print
  print('✓ sup-count: 8 דוגמאות (6 חוזה + חוק-17 + שרשור) — ירוק');
}
