"""אפליקציית אישורי-מעבר למירון — כבסיס-ידע לסוגיא הסמלית.
כל מקור אמיתי: דברי-הבעלים · ממצאי-החיפוש בגוגל (מסומנים כמעשה) · סברא. אפס המצאה.
הדין המרכזי: "האפליקציה_מכריעה_במחסום" — האם מסך האפליקציה הוא שמכריע אם רכב עובר."""
from yeshiva import (AMORA, BRAITA, KATUV, MISHNA, SEVARA, HAVA_AMINA, MAASEH,
                     Case, Geder, KnowledgeBase, Rule, YeshivaEngine, source)

kb = KnowledgeBase()
kb.dimension("מקור_אמת", "טלפון_האזרח", "מכשיר_המחסום", "השרת", severity=True)
kb.dimension("רשת", "אין", "יש")
kb.dimension("רגע", "הנפקה", "מעבר", "יציאה")
kb.dimension("תפקיד", "אזרח", "שוטר")

# ── מקורות ──
בעלים = source("הבעלים 18.9: «אפליקציה מלאה שבאפליקציה הזאת השתמשו גם השוטרים וגם ירשמו אליו»", KATUV)
מחסום = source("חיפוש: במחסום בודקים תעודות של כל הנוסעים ברכב מול רשימות; מי שאינו מופיע אינו עובר, גם אם אינו נוסע להילולה", AMORA, kind=MAASEH)
מסלול = source("חיפוש: תושבי הסביבה נוסעים במסלולים מוגדרים בלבד, בהצגת תעודה ונספח מעודכן עם מקום המגורים", AMORA, kind=MAASEH)
כרטיס = source("חיפוש: כרטיס-הכניסה נקנה מראש, נושא שעה רשומה, ומגביל לחמש שעות בהר; שלושה סוגים לפי אופן ההגעה", AMORA, kind=MAASEH)
אסון = source("חיפוש: אסון מירון 2021 — 45 הרוגים · 102 פצועים מתדחוקת-קהל", AMORA, kind=MAASEH)
ועדה = source("חיפוש: ועדת-החקירה הממלכתית — הממשלה קיבלה החלטות על ניהול ההר, ובפועל כמעט שום החלטה לא בוצעה", MISHNA)
אין_מערכת = source("חיפוש+ריפו: לא נמצאה אפליקציה שמנפיקה אישורי-מעבר; «מירון» ⇒ 0 מופעים בשלושת הריפו", AMORA, kind=MAASEH)
נוחות = source("הנחת-הנוחות: האזרח מציג מסך בטלפון והשוטר מסתכל — כמו תו ירוק", HAVA_AMINA)
סברא = source("סברא", SEVARA)

# ── הדין: האפליקציה מכריעה במחסום ──
kb.claim("האפליקציה_מכריעה_במחסום", True, נוחות, Case.of(מקור_אמת="טלפון_האזרח"), "מציג מסך, השוטר מאשר")
kb.claim("האפליקציה_מכריעה_במחסום", False, מחסום, Case.of(מקור_אמת="טלפון_האזרח"), "בודקים תעודות של כל הנוסעים מול רשימות — לא מסך של נוסע אחד")
kb.claim("האפליקציה_מכריעה_במחסום", True, מחסום, Case.of(מקור_אמת="מכשיר_המחסום"), "הרשימה היא מקור-הבדיקה; המכשיר שמחזיק אותה מכריע")
kb.claim("האפליקציה_מכריעה_במחסום", False, מחסום, Case.of(רשת="אין", מקור_אמת="השרת"), "מחסום בלי רשת אינו יכול לשאול שרת, והתור לא עוצר")
kb.claim("האפליקציה_מכריעה_במחסום", True, בעלים, Case.of(תפקיד="שוטר"), "השוטרים משתמשים בה — היא כלי-הכרעה ולא צפייה")
kb.claim("האפליקציה_מכריעה_במחסום", False, בעלים, Case.of(תפקיד="אזרח"), "האזרח נרשם; רישום אינו הכרעה")
kb.rule(Case.of(מקור_אמת="מכשיר_המחסום", רשת="אין"), "האפליקציה_מכריעה_במחסום", True, סברא,
        "מכשיר-מחסום עם רשימה מורדת-מראש מכריע גם בלי רשת")

# ── הדין: אפשר לעבוד בלי רשת ──
kb.claim("חייב_לעבוד_בלי_רשת", True, מחסום, Case.of(רגע="מעבר"), "הבדיקה קורית בכביש הר, והתור אינו עוצר כשהרשת נופלת")
kb.claim("חייב_לעבוד_בלי_רשת", False, סברא, Case.of(רגע="הנפקה"), "הנפקה נעשית מראש, מהבית, עם רשת")
kb.claim("חייב_לעבוד_בלי_רשת", True, ועדה, Case.of(רגע="מעבר"), "החלטה שלא בוצעה בפועל היא החלטה שלא הייתה")

# ── הדין: המספר בפנים ידוע ──
kb.claim("המספר_בפנים_ידוע", True, כרטיס, Case.of(רגע="מעבר"), "שעה רשומה + חמש שעות ⇒ אפשר לדעת מי אמור להיות בפנים")
kb.claim("המספר_בפנים_ידוע", False, סברא, Case.of(רגע="מעבר"), "כניסה בלי יציאה סופרת רק חצי — המספר גדל ולא קטן")
kb.claim("המספר_בפנים_ידוע", True, סברא, Case.of(רגע="יציאה"), "רק רישום-יציאה סוגר את המאזן")
kb.claim("המספר_בפנים_ידוע", False, אסון, Case.of(רגע="מעבר"), "45 הרוגים מתדחוקת-קהל — הצפיפות בפנים היא הסכנה, לא הכניסה")

# ── חקירה: מהי האפליקציה — טופס-הנפקה או שולט-כניסה ──
טופס = Geder("האפליקציה = מנפיק-אישורים",
    (Rule(Case.of(רגע="הנפקה"), "חייב_לעבוד_בלי_רשת", False, סברא),
     Rule(Case.of(מקור_אמת="טלפון_האזרח"), "האפליקציה_מכריעה_במחסום", True, סברא)),
    "מרכזה בטופס ובזכאות; המחסום רק קורא את מה שהונפק.")
שולט = Geder("האפליקציה = שולט-כניסה בזמן-אמת",
    (Rule(Case.of(רגע="מעבר"), "חייב_לעבוד_בלי_רשת", True, סברא),
     Rule(Case.of(מקור_אמת="טלפון_האזרח"), "האפליקציה_מכריעה_במחסום", False, סברא)),
    "מרכזה ברגע-המעבר ובמספר-שבפנים; ההנפקה היא שלב-קלט בתוכה.")
kb.chakira("מהי האפליקציה", טופס, שולט)

if __name__ == "__main__":
    e = YeshivaEngine(kb)
    print(e.sugya("סוגיא דאישור-מעבר למירון"))
    print()
    for c in (Case.of(מקור_אמת="טלפון_האזרח", תפקיד="שוטר"),
              Case.of(מקור_אמת="מכשיר_המחסום", רשת="אין", רגע="מעבר"),
              Case.of(מקור_אמת="השרת", רשת="אין", רגע="מעבר")):
        print(e.ask("האפליקציה_מכריעה_במחסום", c)); print()
    print(e.ask("חייב_לעבוד_בלי_רשת", Case.of(רגע="מעבר"))); print()
    print(e.ask("חייב_לעבוד_בלי_רשת", Case.of(רגע="הנפקה"))); print()
    print(e.ask("המספר_בפנים_ידוע", Case.of(רגע="מעבר"))); print()
    print(e.ask("המספר_בפנים_ידוע", Case.of(רגע="יציאה")))
