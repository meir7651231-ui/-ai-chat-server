"""המשך סוגיית מירון — הכרעת-הבעלים החדשה: ההרשאות הן דאטה, לא קוד.
«אני בונה בשביל המשטרה, אבל אתה לא צריך לרשום; אפליקציה מלאה עם הרשאות מלאות,
ומי שיקנה יכריע מי יש לו הרשאות למה וכמה»."""
import sys
sys.path.insert(0, "/tmp/claude-0/-home-user/f7fc857c-d0a9-5552-9b86-ed0f0b4bc3b7/scratchpad/verify")
from yeshiva import (AMORA, BRAITA, KATUV, MISHNA, SEVARA, HAVA_AMINA, MAASEH,
                     Case, Geder, KnowledgeBase, Rule, YeshivaEngine, source)

kb = KnowledgeBase()
kb.dimension("הרשאות", "צרובות", "דאטה", severity=True)
kb.dimension("לקוח", "המשטרה", "לקוח_אחר")
kb.dimension("רגע", "הנפקה", "מעבר", "יציאה")
kb.dimension("מקור_אמת", "טלפון_האזרח", "מכשיר_המחסום", "השרת")

בעלים_הרשאות = source("הבעלים 18.9: «אפליקציה מלאה עם הרשאות מלאות, ואחר כך מי שיקנה יכריע מי יש לו הרשאות למה וכמה»", KATUV)
בעלים_משטרה = source("הבעלים 18.9: «אני בונה את האפליקציה בשביל המשטרה אבל אתה לא צריך לרשום»", KATUV)
חוק20 = source("LAW.md §20-ג: אפס המצאת-דאטה; שדה בלי מקור = מתג-לבעלים", MISHNA)
מחסום = source("חיפוש: במחסום בודקים תעודות של כל הנוסעים ברכב מול רשימות", AMORA, kind=MAASEH)
מסלול = source("חיפוש: תושבי הסביבה נוסעים במסלולים מוגדרים בלבד, בהצגת תעודה ונספח מגורים", AMORA, kind=MAASEH)
זכאים = source("חיפוש: זכאים שונים — תושבי מירון · תושבי היישובים סביב · אורחי אכסניות רשומים · בעלי-אישור", AMORA, kind=MAASEH)
צריבה = source("הנחת-הנוחות: לצרוב «שוטר» ו«אזרח» בקוד — מהר יותר", HAVA_AMINA)
סברא = source("סברא", SEVARA)

kb.claim("ההרשאות_דאטה", True, בעלים_הרשאות, Case.of(לקוח="לקוח_אחר"), "מי שיקנה יכריע")
kb.claim("ההרשאות_דאטה", True, בעלים_הרשאות, Case.of(לקוח="המשטרה"), "גם אצל המשטרה — «לא צריך לרשום»")
kb.claim("ההרשאות_דאטה", False, צריבה, Case.of(לקוח="המשטרה"), "לקוח יחיד ⇒ לצרוב")
kb.claim("ההרשאות_דאטה", True, חוק20, Case.of(), "שם-תפקיד שנכתב בקוד הוא דאטה מומצאת")
kb.claim("ההרשאות_דאטה", True, זכאים, Case.of(), "ארבעה סוגי-זכאות שונים, וכל אתר יגדיר אחרת")

kb.claim("הזכאות_כלל_ולא_רשימה", True, מסלול, Case.of(רגע="מעבר"), "מסלול מותר + נספח-מגורים = כלל, לא שם ברשימה")
kb.claim("הזכאות_כלל_ולא_רשימה", True, זכאים, Case.of(), "«תושב היישובים סביב» הוא תנאי, לא שם")
kb.claim("הזכאות_כלל_ולא_רשימה", False, מחסום, Case.of(רגע="מעבר", מקור_אמת="מכשיר_המחסום"), "במחסום בודקים מול רשימה — הכלל חייב להיות מוכרע-מראש לשמות")
kb.rule(Case.of(רגע="הנפקה"), "הזכאות_כלל_ולא_רשימה", True, סברא, "בהנפקה מפעילים את הכלל; במחסום קוראים את התוצאה")

כלל = Geder("זכאות = כלל שנבדק ברגע האמת",
    (Rule(Case.of(רגע="מעבר"), "הזכאות_כלל_ולא_רשימה", True, סברא),),
    "המחסום מריץ את הכלל על הנוסע.")
רשימה = Geder("זכאות = רשימה שהוכרעה מראש",
    (Rule(Case.of(רגע="מעבר"), "הזכאות_כלל_ולא_רשימה", False, סברא),
     Rule(Case.of(רגע="הנפקה"), "הזכאות_כלל_ולא_רשימה", True, סברא)),
    "הכלל רץ בהנפקה ומייצר רשימה; המחסום קורא רשימה בלבד.")
kb.chakira("מהי זכאות", כלל, רשימה)

if __name__ == "__main__":
    e = YeshivaEngine(kb)
    print(e.sugya("סוגיא דהרשאות ומהות-הזכאות"))
    print()
    print(e.ask("ההרשאות_דאטה", Case.of(לקוח="המשטרה"))); print()
    print(e.ask("הזכאות_כלל_ולא_רשימה", Case.of(רגע="מעבר", מקור_אמת="מכשיר_המחסום"))); print()
    print(e.ask("הזכאות_כלל_ולא_רשימה", Case.of(רגע="הנפקה")))
