"""המשפט של הדובר (הדוח, המלון, המצגת, הפרויקט, החופש, אשתו) — כבסיס-ידע לסוגיא הסמלית. אותו מנוע, אותם מהלכים.
כל טענה כאן היא ציטוט מהמשפט; הממדים נגזרים ממה שנאמר (מועד · מי מחכה · הבטחה קוימה · הדבר נסגר)."""
from yeshiva import (AMORA, BRAITA, KATUV, SEVARA, MAASEH, Case, Geder, KnowledgeBase, Rule, YeshivaEngine, source)

kb = KnowledgeBase()
kb.dimension("מועד", "אין", "יום_ראשון", "מחר", severity=True)   # ככל שהמועד קרוב — התביעה חזקה יותר
kb.dimension("מי_מחכה", "אף_אחד", "הצוות", "המנהל")
kb.dimension("הבטחה_קוימה", "לא", "כן", "לא_ידוע")
kb.dimension("נסגר", "לא", "כן")

הדובר = source("הדובר (המשפט)", AMORA)
אשתו = source("אשתו, אתמול בלילה", AMORA)
אני = source("אני, בבית הקפה", AMORA)
המלון = source("מה שהבטיחו במלון", AMORA)
הפרויקט = source("מה שהבטיחו בפרויקט החדש", AMORA)
העבודה = source("החופש שהבטיחו בעבודה לפני חצי שנה", BRAITA)
מעשה = source("מה שקרה בפועל", AMORA, kind=MAASEH)
סברא = source("סברא", SEVARA)

# מה לעשות עכשיו — הדין: "לעשות_עכשיו"
kb.claim("לעשות_עכשיו", True, הדובר, Case.of(מועד="מחר", מי_מחכה="המנהל"), "הדוח שהבטחתי לשלוח למנהל שלי לפני הפגישה מחר")
kb.claim("לעשות_עכשיו", True, הדובר, Case.of(מועד="יום_ראשון", מי_מחכה="הצוות"), "המצגת שהבטחתי לצוות עד יום ראשון")
kb.claim("לעשות_עכשיו", False, אשתו, Case.of(נסגר="לא"), "אם אני ממשיך לקחת על עצמי עוד ועוד בלי לסגור כלום, בסוף אני אשבור את עצמי")
kb.claim("לעשות_עכשיו", True, אשתו, Case.of(מועד="אין", מי_מחכה="אף_אחד"), "אולי כדאי שאקח סוף־סוף את החופש")
kb.claim("לעשות_עכשיו", False, סברא, Case.of(מועד="אין"), "תמיד היה משהו דחוף יותר")

# האם לסמוך על הבטחה — הדין: "לסמוך_על_הבטחה"
kb.claim("לסמוך_על_הבטחה", True, המלון, Case.of(הבטחה_קוימה="לא_ידוע"), "הבטיחו לי מראש שהמלון פנוי")
kb.claim("לסמוך_על_הבטחה", False, מעשה, Case.of(הבטחה_קוימה="לא"), "בניגוד למה שהבטיחו לי מראש, המלון לא באמת היה פנוי")
kb.claim("לסמוך_על_הבטחה", True, הפרויקט, Case.of(הבטחה_קוימה="לא_ידוע"), "הבטיחו לי שם גמישות בשעות")
kb.claim("לסמוך_על_הבטחה", False, הדובר, Case.of(הבטחה_קוימה="לא_ידוע"), "אני כבר לא יודע אם אני מאמין להבטחות האלה בכלל")
kb.claim("לסמוך_על_הבטחה", False, אני, Case.of(הבטחה_קוימה="לא_ידוע"), "אם רק הייתי בודק שוב את כל הפרטים לפני שאישרתי")
kb.rule(Case.of(הבטחה_קוימה="כן"), "לסמוך_על_הבטחה", True, סברא, "הבטחה שקוימה — סומכים")

# חקירה: מהי הבטחה — התחייבות (מחייבת עד שהופרה) או כוונה (לא מחייבת עד שקוימה)
התחייבות = Geder("הבטחה = התחייבות",
    (Rule(Case.of(הבטחה_קוימה="לא_ידוע"), "לסמוך_על_הבטחה", True, סברא),
     Rule(Case.of(הבטחה_קוימה="לא"), "לסמוך_על_הבטחה", False, סברא)),
    "המבטיח חייב; סומכים עד שיופר.")
כוונה = Geder("הבטחה = כוונה",
    (Rule(Case.of(הבטחה_קוימה="לא_ידוע"), "לסמוך_על_הבטחה", False, סברא),
     Rule(Case.of(הבטחה_קוימה="כן"), "לסמוך_על_הבטחה", True, סברא)),
    "המבטיח מתכוון; סומכים רק אחרי שקוים או נבדק.")
kb.chakira("מהות ההבטחה", התחייבות, כוונה)

if __name__ == "__main__":
    e = YeshivaEngine(kb)
    print(e.sugya("סוגיא דהדובר — מה קודם ועל מה סומכים"))
    print()
    print(e.ask("לעשות_עכשיו", Case.of(מועד="מחר", מי_מחכה="המנהל", נסגר="לא")))
    print()
    print(e.ask("לעשות_עכשיו", Case.of(מועד="אין", מי_מחכה="אף_אחד", נסגר="לא")))
    print()
    print(e.ask("לסמוך_על_הבטחה", Case.of(הבטחה_קוימה="לא_ידוע")))
