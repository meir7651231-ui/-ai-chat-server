"""השאלה שלי — איפה חי המהלך הישיבתי כשהוא שזור במחולל — כבסיס-ידע לסוגיא הסמלית.
כל טענה = מקור אמיתי מהלילה (מדידה · מסמך של הישיבה · הכרעת-בעלים), בדרגה שלו."""
from yeshiva import (AMORA, BRAITA, KATUV, SEVARA, MAASEH, Case, Geder, KnowledgeBase, Rule, YeshivaEngine, source)

kb = KnowledgeBase()
kb.dimension("החלטה", "דטרמיניסטית", "בין_מועמדים")        # פסק לפי כלל (כמו «אין») מול בחירה בין שניים/טענה
kb.dimension("למידה_מדווחת", "לא", "כן")                    # הפסק חוזר לפנקס הזרעים (asked/changed)?
kb.dimension("קריאות", "בקשה_אחת_לריצה", "לכל_נקודה")       # כמה פעמים פונים לישיבה בריצה אחת

בעלים = source("הבעלים: «שזור לאורך כל הדרך, כל מנוע וכל צעד» (+כלל-הכפילות — הסקה שלי)", KATUV)
תכנון = source("README של הישיבה: מילון פעם אחת · זרעים שלומדים · חיבור לסוכן דרך hooks", BRAITA)
מפת_דרכים = source("ROADMAP §3: המנוע הוא הלולאה החיצונית והמודל כלי שלו", BRAITA)
ניסוי = source("מדידה: 27 שורות JS ב-particles.mjs — הפלט השתנה, 0 דיווח לפנקס", AMORA, kind=MAASEH)
מדידת_זמן = source("מדידה: קריאה לישיבה 0.099s (import 0.065s)", AMORA, kind=MAASEH)
קריסה = source("מבחן הקריסה (kasad): מהלכים inline ב-JS ≡ הישיבה הקטנה שנדחתה", AMORA, kind=MAASEH)
סברא = source("סברא", SEVARA)

# הדין: "המהלך_רץ_בתוך_המנוע" (בשפת המנוע, לא בפייתון)
kb.claim("המהלך_רץ_בתוך_המנוע", True, בעלים, Case.of(החלטה="דטרמיניסטית"), "שזור בכל מנוע ובכל צעד — לא מחובר")
kb.claim("המהלך_רץ_בתוך_המנוע", True, ניסוי, Case.of(החלטה="דטרמיניסטית", למידה_מדווחת="לא"), "«אין» הפך לפסק על 8 מקורות, בתוך המנוע, בלי לקרוא לפייתון")
kb.claim("המהלך_רץ_בתוך_המנוע", False, תכנון, Case.of(למידה_מדווחת="לא"), "הזרעים לומדים מ-asked/changed; מהלך שלא מדווח — לא לומד")
kb.claim("המהלך_רץ_בתוך_המנוע", False, קריסה, Case.of(למידה_מדווחת="לא"), "inline בלי פנקס ≡ הישיבה הקטנה — הבעלים דחה אותה")
kb.claim("המהלך_רץ_בתוך_המנוע", False, מפת_דרכים, Case.of(החלטה="בין_מועמדים"), "הישיבה היא הלולאה החיצונית; מי שמחליט בין מועמדים עובר דרכה")
kb.claim("המהלך_רץ_בתוך_המנוע", True, מדידת_זמן, Case.of(קריאות="לכל_נקודה"), "0.1s לקריאה × אלפי נקודות = דקות — לא לכל נקודה")
kb.claim("המהלך_רץ_בתוך_המנוע", False, מדידת_זמן, Case.of(קריאות="בקשה_אחת_לריצה"), "בקשה אחת לריצה = שניות — אפשר לפנות לישיבה")
ממשק = source("מדידה: הישיבה חושפת ממשק — KnowledgeBase.claim/ask ⇒ Answer(outcome, trace.to_dict) · gate קורא JSON מ-stdin", AMORA, kind=MAASEH)
kb.claim("המהלך_רץ_בתוך_המנוע", False, ממשק, Case.of(החלטה="בין_מועמדים"), "מנוע יכול לבנות בסיס-ידע ולשאול; אין צורך לשכפל את המהלך")
kb.rule(Case.of(למידה_מדווחת="כן", החלטה="דטרמיניסטית"), "המהלך_רץ_בתוך_המנוע", True, סברא, "פסק לפי כלל שמדווח — רץ במקום שבו ההחלטה")

# חקירה: מהו המהלך — כלל (חי במקום ההחלטה) או שאלה (חיה אצל השואל ולומדת)
כלל = Geder("המהלך = כלל",
    (Rule(Case.of(החלטה="דטרמיניסטית"), "המהלך_רץ_בתוך_המנוע", True, סברא),
     Rule(Case.of(החלטה="בין_מועמדים"), "המהלך_רץ_בתוך_המנוע", True, סברא)),
    "המהלך הוא כלל-פסיקה; חי במקום שבו מחליטים, בשפת המחליט.")
שאלה = Geder("המהלך = שאלה",
    (Rule(Case.of(למידה_מדווחת="לא"), "המהלך_רץ_בתוך_המנוע", False, סברא),
     Rule(Case.of(החלטה="בין_מועמדים"), "המהלך_רץ_בתוך_המנוע", False, סברא)),
    "המהלך הוא שאלה שלומדת אם היא שווה; חיה אצל הישיבה, והמנוע פונה אליה.")
kb.chakira("מהות המהלך הישיבתי", כלל, שאלה)

