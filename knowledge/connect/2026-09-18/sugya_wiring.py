    print()
    print(e.ask("המהלך_רץ_בתוך_המנוע", Case.of(החלטה="דטרמיניסטית", למידה_מדווחת="לא")))
    print()
    print(e.ask("המהלך_רץ_בתוך_המנוע", Case.of(החלטה="בין_מועמדים", קריאות="בקשה_אחת_לריצה")))
