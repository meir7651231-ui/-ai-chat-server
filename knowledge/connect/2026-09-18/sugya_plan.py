"""תוכנית להשלמת המחולל — הסוגיא שמכריעה את צורתה.
הדין המרכזי: "המחולל_שלם". החקירה: מהו «מאה אחוז» — כל המנועים ירוקים, או משפט⇒אפליקציה עובדת?
כל מקור אמיתי: ציטוט-בעלים · LAW/THE-WAY · מדידה מהיום (kind=MAASEH)."""
from yeshiva import (AMORA, BRAITA, KATUV, MISHNA, SEVARA, HAVA_AMINA, MAASEH,
                     Case, Geder, KnowledgeBase, Rule, YeshivaEngine, source)

kb = KnowledgeBase()
kb.dimension("מדד", "שערים_ירוקים", "משפט_לאפליקציה", severity=True)
kb.dimension("כיסוי", "משפט_אחד", "כל_משפט", severity=True)
kb.dimension("ישיבה", "נקודה_אחת", "כל_מנוע", severity=True)
kb.dimension("דיווח", "לא", "כן")

# ── מקורות ──
בעלים22 = source("הכרעה-22 (ציטוט-בעלים): משפט חופשי ⇒ אפליקציה עובדת 100%", KATUV)
בעלים_שזור = source("הבעלים 18.9: «לא מחובר — שזור לאורך כל הדרך, כל מנוע וכל צעד»", KATUV)
בעלים_כל = source("הבעלים: «לא מטרה ספציפית אלא כל מטרה» · «כל משפט, תזכור את המשפטים המשוגעים»", KATUV)
בעלים_חתיכה = source("הבעלים 18.9: «אתה לא שלחת אותו על התוכנית עבודה» — חתיכה אינה השלם", KATUV)
חוק23 = source("LAW.md הכרעה-23: פירוק לפעולות-יסוד · «אין אטום מוכן ≠ אי-אפשר» · «אין = לא-חיפשת»", MISHNA)
הדרך = source("THE-WAY.md: 7 צעדים + אימות-מול-המטרה («האם זה באמת משיג את המטרה», לא «מתקמפל»)", MISHNA)
לקח110 = source("LEARNINGS L110: נתיב-ברירת-מחדל קשיח לא נכשל — הוא מדלג; ירוק-חלול אינו ירוק", BRAITA)
שערים = source("58 השערים ירוקים היום (police --fast: 45 ran · 0 failed)", HAVA_AMINA)
m_goal = source("מדידה 18.9: --goal על טקסט חופשי ⇒ 8/8 צעדים · exit 0 · 0.7-4.1s", AMORA, kind=MAASEH)
m_liba = source("מדידה 18.9: ליבה ⇒ 12 תביעות · 0 צרכים · 13 מתגי-בעלים", AMORA, kind=MAASEH)
m_322 = source("מדידה: perok-scan על הריפו ⇒ 322 יחידות · 173 עם צרכים · 149 עם 0", AMORA, kind=MAASEH)
m_class = source("מדידה: classOf על 7 ישויות-ליבה ⇒ 6 ריקות (שיחה⇒CallEntry היחידה)", AMORA, kind=MAASEH)
m_43 = source("מדידה: 5 מ-43 מנועי-חיפוש מזכירים ורמינהו/--none; 38 לא", AMORA, kind=MAASEH)
m_pinkas = source("מדידה: 27 שורות ורמינהו ב-particles.mjs פסקו על 8 מקורות ו-0 דיווח לפנקס", AMORA, kind=MAASEH)
סברא = source("סברא", SEVARA)

# ── הדין: המחולל שלם ──
kb.claim("המחולל_שלם", True, שערים, Case.of(מדד="שערים_ירוקים"), "כל השערים עוברים")
kb.claim("המחולל_שלם", False, בעלים22, Case.of(מדד="שערים_ירוקים"), "המדד הוא אפליקציה עובדת, לא שער")
kb.claim("המחולל_שלם", False, הדרך, Case.of(מדד="שערים_ירוקים"), "אימות מול-המטרה, לא מול «מתקמפל»")
kb.claim("המחולל_שלם", False, לקח110, Case.of(מדד="שערים_ירוקים"), "ירוק שמדלג נראה כמו «אין מה למדוד»")
kb.claim("המחולל_שלם", False, m_liba, Case.of(מדד="משפט_לאפליקציה"), "ליבה: 0 צרכים ⇒ 0 אפליקציה")
kb.claim("המחולל_שלם", False, m_322, Case.of(כיסוי="כל_משפט"), "149 מ-322 מחזירות 0")
kb.claim("המחולל_שלם", True, m_goal, Case.of(כיסוי="משפט_אחד"), "המסלול רץ מקצה לקצה, exit 0")
kb.claim("המחולל_שלם", False, בעלים_כל, Case.of(כיסוי="משפט_אחד"), "לא מטרה ספציפית אלא כל מטרה")
kb.claim("המחולל_שלם", False, בעלים_שזור, Case.of(ישיבה="נקודה_אחת"), "שזור בכל מנוע ובכל צעד")
kb.claim("המחולל_שלם", False, m_pinkas, Case.of(דיווח="לא"), "מהלך בלי דיווח = חצי מהלך")
kb.claim("המחולל_שלם", False, m_43, Case.of(ישיבה="נקודה_אחת"), "38 מנועים אומרים «אין» בלי ורמינהו")
kb.rule(Case.of(מדד="משפט_לאפליקציה", כיסוי="כל_משפט", ישיבה="כל_מנוע", דיווח="כן"),
        "המחולל_שלם", True, סברא, "אפליקציה עובדת מכל משפט, הישיבה בכל מנוע, והכל בפנקס")

# ── הדין: האם הפער היחיד הוא המדף ──
kb.claim("הפער_היחיד_הוא_המדף", True, m_class, Case.of(כיסוי="משפט_אחד"), "6 ישויות-ליבה חסרות ⇒ 0 צרכים")
kb.claim("הפער_היחיד_הוא_המדף", False, m_322, Case.of(כיסוי="כל_משפט"), "149 יחידות, לא רק ליבה")
kb.claim("הפער_היחיד_הוא_המדף", False, m_43, Case.of(ישיבה="נקודה_אחת"), "«אין» בלי חיפוש אינו חוסר-במדף")
kb.claim("הפער_היחיד_הוא_המדף", False, בעלים_חתיכה, Case.of(כיסוי="כל_משפט"), "חתיכה אינה השלם")

# ── חקירה: מהו «מאה אחוז» ──
מנועים = Geder("100% = כל המנועים ירוקים",
    (Rule(Case.of(מדד="שערים_ירוקים"), "המחולל_שלם", True, סברא),
     Rule(Case.of(כיסוי="משפט_אחד"), "המחולל_שלם", True, סברא)),
    "שלמות = מצב-המנועים. מודדים את הכלי.")
אפליקציה = Geder("100% = כל משפט ⇒ אפליקציה עובדת",
    (Rule(Case.of(מדד="שערים_ירוקים"), "המחולל_שלם", False, סברא),
     Rule(Case.of(כיסוי="משפט_אחד"), "המחולל_שלם", False, סברא)),
    "שלמות = התוצר על כל קלט. מודדים את הפלט.")
kb.chakira("מהו «מאה אחוז»", מנועים, אפליקציה)

if __name__ == "__main__":
    e = YeshivaEngine(kb)
    print(e.sugya("סוגיא דהשלמת המחולל"))
    print()
    for c in (Case.of(מדד="שערים_ירוקים", כיסוי="משפט_אחד"),
              Case.of(מדד="משפט_לאפליקציה", כיסוי="כל_משפט", ישיבה="נקודה_אחת", דיווח="לא"),
              Case.of(מדד="משפט_לאפליקציה", כיסוי="כל_משפט", ישיבה="כל_מנוע", דיווח="כן")):
        print(e.ask("המחולל_שלם", c)); print()
    print(e.ask("הפער_היחיד_הוא_המדף", Case.of(כיסוי="כל_משפט")))
