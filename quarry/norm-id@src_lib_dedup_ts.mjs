export function normId(s) {
    const d = (s || '').replace(/\D/g, '');
    if (!d || /^0+$/.test(d))
        return '';
    // מציין-מקום נדרים מרופד: "000000020"/"000000065" — עוברים את /^0+$/ אך אינם ת"ז.
    // אם אחרי הסרת אפסים-מובילים נשארות <4 ספרות-משמעותיות ⇒ לא מפתח.
    if (d.replace(/^0+/, '').length < 4)
        return '';
    return d.length >= 5 ? d : '';
}
