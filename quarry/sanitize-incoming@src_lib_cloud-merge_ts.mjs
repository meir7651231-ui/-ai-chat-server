export function sanitizeIncoming(col, item) {
    const fields = LIST_FIELDS[col];
    if (!fields)
        return item;
    let out = item;
    for (const f of fields) {
        if (!Array.isArray(out[f]))
            out = { ...out, [f]: [] };
    }
    return out;
}
